#!/usr/bin/env node
/**
 * Build public/src/vendor/emoji-data.js from emojibase-data’s en/data.json
 * (Unicode CLDR names and keywords, MIT).
 *
 *   curl -sfLO https://cdn.jsdelivr.net/npm/emojibase-data@17.0.0/en/data.json
 *   node scripts/build-emoji-data.mjs data.json
 *
 * Keeps emoji up to MAX_VERSION so older phones don’t show empty boxes, drops
 * skin-tone variants and the component group, and writes one compact row per
 * emoji: [emoji, name, "keyword keyword …", groupIndex].
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_VERSION = "emojibase-data@17.0.0";
const MAX_VERSION = 15;
const COMPONENT_GROUP = 2;

const inputPath = process.argv[2];
if (!inputPath) {
  console.error("Usage: node scripts/build-emoji-data.mjs <path to en/data.json>");
  process.exit(1);
}

const source = JSON.parse(readFileSync(inputPath, "utf8"));
const rows = source
  .filter(
    (e) =>
      typeof e.group === "number" &&
      e.group !== COMPONENT_GROUP &&
      typeof e.version === "number" &&
      e.version <= MAX_VERSION
  )
  .sort((a, b) => a.order - b.order)
  .map((e) => [e.emoji, e.label, (e.tags ?? []).join(" "), e.group]);

const outPath = join(
  dirname(fileURLToPath(import.meta.url)),
  "../public/src/vendor/emoji-data.js"
);
const body = rows.map((row) => JSON.stringify(row)).join(",\n");
writeFileSync(
  outPath,
  `// Generated by scripts/build-emoji-data.mjs from ${SOURCE_VERSION} (MIT,
// Unicode CLDR data). Emoji up to version ${MAX_VERSION}. Do not edit by hand.
// Row: [emoji, name, keywords, emojibase group index]
export default [
${body}
];
`
);
console.log(`Wrote ${rows.length} emoji to ${outPath}`);
